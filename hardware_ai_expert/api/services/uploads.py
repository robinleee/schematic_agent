"""Bounded upload staging; never derive a path from an untrusted filename."""
from __future__ import annotations
import os
import json
import stat
import tempfile
import time
from pathlib import Path
from uuid import uuid4

from fastapi import HTTPException, UploadFile
from .etl_jobs import _owner_alive, _process_start

CHUNK = 64 * 1024
ETL_LIMIT = 20 * 1024 * 1024
KNOWLEDGE_LIMIT = 20 * 1024 * 1024
ETL_SUFFIXES = {
    "pstxnet": {".dat", ".pstxnet"},
    "pstxprt": {".dat", ".pstxprt"},
    "pstchip": {".dat", ".pstchip"},
    "bom": {".csv", ".xlsx", ".xls"},
}
_staging = None
_staging_owner = None
_ALL_SUFFIXES = set().union(*ETL_SUFFIXES.values(), {".pdf", ".txt"})


def _root():
    # Private directory, not the shared /tmp namespace. Never scan arbitrary /tmp files.
    root = Path(os.environ.get(
        "UPLOAD_STAGING_DIR", Path(__file__).resolve().parents[3] / "data" / "uploads"))
    root.mkdir(mode=0o700, parents=True, exist_ok=True)
    info = root.lstat()
    if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.getuid() or info.st_mode & 0o077:
        raise RuntimeError("Upload staging directory must be private to the service user")
    return root


def _directory():
    global _staging, _staging_owner
    owner = (os.getpid(), _process_start(), str(_root()))
    reclaim_orphans()
    if owner != _staging_owner:
        root = Path(owner[2])
        directory = Path(tempfile.mkdtemp(prefix="worker-", dir=str(root)))
        marker = directory / ".owner"
        marker.write_text(json.dumps({"pid": owner[0], "start": owner[1]}))
        _staging, _staging_owner = directory, owner
    return _staging


def reclaim_orphans(grace_seconds=3600, max_dirs=128, max_files=8):
    """Best-effort bounded cleanup of *our* dead worker's old, regular upload files.

    An active owner's files are never removed, even when old. Legacy shared-/tmp
    uploads without a private owner marker cannot be safely identified or reclaimed.
    """
    root = _root()
    removed = 0
    for index, directory in enumerate(root.iterdir()):
        if index >= max_dirs:
            break
        if not directory.name.startswith("worker-") or directory.is_symlink() or not directory.is_dir():
            continue
        try:
            info = json.loads((directory / ".owner").read_text())
            if not isinstance(info["pid"], int) or not isinstance(info["start"], str):
                continue
            if _owner_alive(info["pid"], info["start"]):
                continue
            # Never load or unlink an unbounded directory, even if metadata looks valid.
            entries = []
            for entry in directory.iterdir():
                entries.append(entry)
                if len(entries) > max_files + 1:  # plus .owner
                    break
            if len(entries) > max_files + 1:
                continue
            if any(entry.name != ".owner" and (
                not entry.name.startswith("hardware-upload-")
                or entry.suffix not in _ALL_SUFFIXES or not entry.is_file()
                or entry.is_symlink()) for entry in entries):
                continue
            if any(time.time() - entry.stat().st_mtime < grace_seconds for entry in entries):
                continue
            # Do not follow symlinks or delete anything not generated by stage().
            for entry in entries:
                entry.unlink()
            directory.rmdir()
            removed += 1
        except (OSError, KeyError, ValueError, TypeError):
            # Missing/incomplete ownership metadata is not evidence of ownership.
            continue
    return removed


async def stage(upload: UploadFile, allowed: set[str], limit: int) -> str:
    suffix = Path(upload.filename or "").suffix.lower()
    if suffix not in allowed:
        raise HTTPException(400, f"Unsupported upload extension: {suffix or '(none)'}")
    path = None
    try:
        with tempfile.NamedTemporaryFile(prefix="hardware-upload-", suffix=suffix,
                                         dir=str(_directory()), delete=False) as out:
            path = out.name
            total = 0
            while chunk := await upload.read(CHUNK):
                total += len(chunk)
                if total > limit:
                    raise HTTPException(413, f"Upload exceeds {limit} bytes")
                out.write(chunk)
        return path
    except BaseException:
        if path:
            os.unlink(path)
        raise
    finally:
        await upload.close()


def cleanup(paths):
    for path in paths:
        try:
            os.unlink(path)
        except FileNotFoundError:
            pass
